//go:build !windows

package polishkit

import (
	"os"
	"syscall"
)

// lockFile takes an exclusive advisory lock on the pass's lock file; the
// returned func releases it. Blocks until another process's transaction on
// the same pass ends.
func lockFile(path string) (func(), error) {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0o644)
	if err != nil {
		return nil, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		_ = f.Close()
		return nil, err
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		_ = f.Close()
	}, nil
}
