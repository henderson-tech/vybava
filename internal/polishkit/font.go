const (
	glyphW = 5
	glyphH = 7
	// glyphGap is the blank column between glyphs.
	glyphGap = 1
)

// textWidth is the pixel width of s at scale.
func textWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return (n*glyphW + (n-1)*glyphGap) * scale
}

// drawText paints s at (x, y) on dst, each glyph pixel scale wide.
func drawText(dst draw.Image, x, y int, s string, scale int, c color.Color) {
	src := image.NewUniform(c)
	for _, r := range s {
		g, ok := glyphs[r]
		if !ok {
			up := []rune(strings.ToUpper(string(r)))[0]
			if g, ok = glyphs[up]; !ok {
				g = glyphs['?']
			}
		}
		for row := 0; row < glyphH; row++ {
			for col := 0; col < glyphW; col++ {
				if g[row][col] != '#' {
					continue
				}
				px := x + col*scale
				py := y + row*scale
				draw.Draw(dst, image.Rect(px, py, px+scale, py+scale), src, image.Point{}, draw.Src)
			}
		}
		x += (glyphW + glyphGap) * scale
	}
}
